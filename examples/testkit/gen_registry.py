#!/usr/bin/env python3
"""Convert native tests and generate a DEV TestKit registry (Python stdlib only).

Public helpers: find_tests(plugin_dir), render_registry(cases),
check_registry(plugin_dir), generate(plugin_dir, rewrite=False). No manifest: the
registry is always checked against the marked functions in the current sources.
Only namespace-level void functions taking one context handle are supported;
unsupported marked declarations fail with a source location.
"""
import argparse
from dataclasses import dataclass
from pathlib import Path
import re
import sys


class RegistryError(ValueError):
    pass


@dataclass(frozen=True)
class TestCase:
    name: str
    path: Path
    marker_start: int
    marker_end: int
    type_start: int
    type_end: int
    native: bool


# Mask comments and literals, preserving offsets and newlines for diagnostics.
LEXEME = re.compile(r'//[^\n]*|/\*[\s\S]*?\*/|"""[\s\S]*?"""|"(?:\\[\s\S]|[^"\\])*"|\'(?:\\[\s\S]|[^\'\\])*\'')
SIGNATURE = re.compile(r'\s*void\s+([A-Za-z_]\w*)\s*\(\s*((?:Tests::Context|TestKit::Ctx))\s*@\s*([A-Za-z_]\w*)\s*\)\s*\{')
NAMESPACE = re.compile(r'\bnamespace\s+([A-Za-z_]\w*(?:::[A-Za-z_]\w*)*)\s*\{')


def mask_source(source):
    comments = []
    def replace(match):
        if match.group().startswith('//'):
            comments.append((match.start(), match.end(), match.group()[2:].strip()))
        return ''.join('\n' if c == '\n' else ' ' for c in match.group())
    return LEXEME.sub(replace, source), comments


def scan_source(path, source):
    masked, comments = mask_source(source)
    markers = []
    for match in re.finditer(r'\[\s*Test\b[^\]]*\]', masked):
        if not re.fullmatch(r'\[\s*Test\s*\]', match.group()):
            raise RegistryError(f'{path}: unsupported [Test] metadata: {match.group()}')
        markers.append((match.start(), match.end(), True))
    markers += [(start, end, False) for start, end, text in comments if text == '[TestKit]']
    markers.sort()
    namespaces = {m.end() - 1: m.group(1) for m in NAMESPACE.finditer(masked)}
    braces = list(re.finditer(r'[{}]', masked))
    stack = []
    cursor = 0
    cases = []
    for start, end, native in markers:
        while cursor < len(braces) and braces[cursor].start() < start:
            brace = braces[cursor]
            if brace.group() == '{':
                stack.append(namespaces.get(brace.start()))
            elif stack:
                stack.pop()
            else:
                raise RegistryError(f'{path}: unmatched closing brace')
            cursor += 1
        line = source.count('\n', 0, start) + 1
        match = SIGNATURE.match(masked, end)
        if match is None or any(part is None for part in stack):
            raise RegistryError(f'{path}:{line}: unsupported test; expected namespace-level void F(Context@ ctx) with a body')
        expected = 'Tests::Context' if native else 'TestKit::Ctx'
        if match.group(2) != expected:
            raise RegistryError(f'{path}:{line}: {"[Test]" if native else "// [TestKit]"} requires {expected}@')
        name = '::'.join([*stack, match.group(1)])
        if name == 'Tests::TestKit_AllRegisteredTests':
            raise RegistryError(f'{path}:{line}: name reserved for generated adapter')
        cases.append(TestCase(name, path, start, end, match.start(2), match.end(2), native))
    return cases


def find_tests(plugin_dir):
    plugin_dir = Path(plugin_dir)
    if not plugin_dir.is_dir():
        raise RegistryError(f'plugin directory does not exist: {plugin_dir}')
    cases = []
    for path in sorted(plugin_dir.rglob('*.as')):
        relative = path.relative_to(plugin_dir)
        if relative == Path('src/_TestRegistry.as') or any(part.startswith('.') for part in relative.parts):
            continue
        cases.extend(scan_source(path, path.read_text(encoding='utf-8')))
    seen = set()
    for case in cases:
        if case.name in seen:
            raise RegistryError(f'duplicate test name: {case.name}')
        seen.add(case.name)
    if not cases:
        raise RegistryError('no registered tests found')
    return sorted(cases, key=lambda case: case.name)


def render_registry(cases):
    lines = ['// Generated by gen_registry.py. Do not edit.', '#if DEV', 'namespace TestKit {',
             '    bool g_TestKitRegistryReady = false;', '    void RegisterAll() {',
             '        if (g_TestKitRegistryReady) return;', '        g_TestKitRegistryReady = true;']
    lines += [f'        ::TestKit::Reg("{case.name}", ::{case.name});' for case in cases]
    # Root-qualify functions/callbacks. AngelScript rejects a leading :: on
    # the CtxSink constructor expression (runtime probe; LSP misses this).
    lines += ['    }', '}', '', 'namespace Tests {', '    [Test]',
              '    void TestKit_AllRegisteredTests(Tests::Context@ ctx) { // lsp: ignore unused',
              '        ::TestKit::RegisterAll();', '        ::TestKit::RunAll(TestKit::CtxSink(ctx));',
              '    }', '}', '#endif', '']
    return '\n'.join(lines)


def check_registry(plugin_dir):
    cases = find_tests(plugin_dir)
    if any(case.native for case in cases):
        raise RegistryError('native [Test] signatures need gen_registry.py --rewrite')
    path = Path(plugin_dir) / 'src/_TestRegistry.as'
    if not path.is_file() or path.read_text(encoding='utf-8') != render_registry(cases):
        raise RegistryError(f'registry drift: regenerate {path}')
    return cases


def generate(plugin_dir, rewrite=False):
    cases = find_tests(plugin_dir)  # Validate every file before any writes.
    if any(case.native for case in cases) and not rewrite:
        raise RegistryError('native [Test] signatures require explicit --rewrite')
    edits = {}
    for case in cases:
        if case.native:
            edits.setdefault(case.path, []).extend([
                (case.marker_start, case.marker_end, '// [TestKit]\n'),
                (case.type_start, case.type_end, 'TestKit::Ctx'),
            ])
    for path, replacements in edits.items():
        source = path.read_text(encoding='utf-8')
        for start, end, text in sorted(replacements, reverse=True):
            source = source[:start] + text + source[end:]
        path.write_text(source, encoding='utf-8')
    registry = Path(plugin_dir) / 'src/_TestRegistry.as'
    registry.parent.mkdir(parents=True, exist_ok=True)
    registry.write_text(render_registry(cases), encoding='utf-8')
    return cases


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--plugin-dir', required=True, type=Path)
    action = parser.add_mutually_exclusive_group()
    action.add_argument('--rewrite', action='store_true', help='convert native [Test] signatures')
    action.add_argument('--check', action='store_true', help='fail on drift; never write')
    args = parser.parse_args(argv)
    try:
        cases = check_registry(args.plugin_dir) if args.check else generate(args.plugin_dir, args.rewrite)
    except (RegistryError, OSError, UnicodeError) as exc:
        print(f'gen_registry: {exc}', file=sys.stderr)
        return 2
    print(f'{len(cases)} tests; registry {"current" if args.check else "generated"}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
